// Convert CIE L*a*b* (D65 illuminant) to sRGB Hex for accurate visual rendering
export function labToRgbHex(L: number, a: number, b: number): string {
  const Xn = 95.047;
  const Yn = 100.0;
  const Zn = 108.883;

  const fy = (L + 16) / 116;
  const fx = a / 500 + fy;
  const fz = fy - b / 200;

  const delta = 6 / 29;

  const fx3 = Math.pow(fx, 3);
  const fy3 = Math.pow(fy, 3);
  const fz3 = Math.pow(fz, 3);

  const x = fx > delta ? fx3 : (fx - 16 / 116) * 3 * Math.pow(delta, 2);
  const y = fy > delta ? fy3 : (fy - 16 / 116) * 3 * Math.pow(delta, 2);
  const z = fz > delta ? fz3 : (fz - 16 / 116) * 3 * Math.pow(delta, 2);

  const X = (x * Xn) / 100;
  const Y = (y * Yn) / 100;
  const Z = (z * Zn) / 100;

  let r = X * 3.2406 + Y * -1.5372 + Z * -0.4986;
  let g = X * -0.9689 + Y * 1.8758 + Z * 0.0415;
  let bl = X * 0.0557 + Y * -0.204 + Z * 1.057;

  r = r > 0.0031308 ? 1.055 * Math.pow(r, 1 / 2.4) - 0.055 : 12.92 * r;
  g = g > 0.0031308 ? 1.055 * Math.pow(g, 1 / 2.4) - 0.055 : 12.92 * g;
  bl = bl > 0.0031308 ? 1.055 * Math.pow(bl, 1 / 2.4) - 0.055 : 12.92 * bl;

  const clamp = (val: number) => Math.max(0, Math.min(255, Math.round(val * 255)));
  const toHex = (n: number) => n.toString(16).padStart(2, '0');

  return `#${toHex(clamp(r))}${toHex(clamp(g))}${toHex(clamp(bl))}`;
}

// Convert sRGB [0-255] to CIE L*a*b* (D65 standard observer)
export function rgbToLab(r: number, g: number, b: number): { L: number; a: number; b: number } {
  let rLin = r / 255;
  let gLin = g / 255;
  let bLin = b / 255;

  rLin = rLin > 0.04045 ? Math.pow((rLin + 0.055) / 1.055, 2.4) : rLin / 12.92;
  gLin = gLin > 0.04045 ? Math.pow((gLin + 0.055) / 1.055, 2.4) : gLin / 12.92;
  bLin = bLin > 0.04045 ? Math.pow((bLin + 0.055) / 1.055, 2.4) : bLin / 12.92;

  const X = (rLin * 0.4124564 + gLin * 0.3575761 + bLin * 0.1804375) * 100;
  const Y = (rLin * 0.2126729 + gLin * 0.7151522 + bLin * 0.0721750) * 100;
  const Z = (rLin * 0.0193339 + gLin * 0.1191920 + bLin * 0.9503041) * 100;

  const Xn = 95.047;
  const Yn = 100.0;
  const Zn = 108.883;

  const f = (t: number) => t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16 / 116;

  const fx = f(X / Xn);
  const fy = f(Y / Yn);
  const fz = f(Z / Zn);

  const L = 116 * fy - 16;
  const aVal = 500 * (fx - fy);
  const bVal = 200 * (fy - fz);

  return {
    L: Number(L.toFixed(2)),
    a: Number(aVal.toFixed(2)),
    b: Number(bVal.toFixed(2))
  };
}

// Compute standard CIE76 color difference
export function deltaE76(
  lab1: { L: number; a: number; b: number },
  lab2: { L: number; a: number; b: number }
): number {
  return Number(Math.sqrt(
    Math.pow(lab1.L - lab2.L, 2) +
    Math.pow(lab1.a - lab2.a, 2) +
    Math.pow(lab1.b - lab2.b, 2)
  ).toFixed(2));
}

