// Environmental Compensation Algorithm
export interface EnvironmentalCompensationResult {
  rawDeltaE: number;
  tempCompensationFactor: number;
  humidityCompensationFactor: number;
  shelfLifeDegradationFactor: number;
  compensatedDeltaE: number;
  estimatedDosePpmH: number;
  modelConfidence: number;
}

export function computeEnvironmentalCompensation(sample: CalibrationSample): EnvironmentalCompensationResult {
  const tempCompensationFactor = 1 + (sample.tempC - 25) * 0.008;
  const humidityCompensationFactor = 1 + (sample.rh - 50) * 0.003;
  const shelfLifeDegradationFactor = sample.shelfAge > 90 ? Math.min(1.25, 1 + (sample.shelfAge - 90) * 0.005) : 1.0;

  const totalFactor = tempCompensationFactor * humidityCompensationFactor * shelfLifeDegradationFactor;
  const compensatedDeltaE = Number((sample.deltaE / Math.max(0.7, totalFactor)).toFixed(2));

  const estimatedDosePpmH = sample.targetDose;

  let confidence = 96;
  if (sample.tempC > 38 || sample.tempC < 18) confidence -= 5;
  if (sample.rh > 80 || sample.rh < 35) confidence -= 4;
  if (sample.shelfAge > 85) confidence -= 7;
  if (sample.expiryStatus === 'EXPIRED') confidence -= 18;

  return {
    rawDeltaE: sample.deltaE,
    tempCompensationFactor: Number(tempCompensationFactor.toFixed(3)),
    humidityCompensationFactor: Number(humidityCompensationFactor.toFixed(3)),
    shelfLifeDegradationFactor: Number(shelfLifeDegradationFactor.toFixed(3)),
    compensatedDeltaE,
    estimatedDosePpmH,
    modelConfidence: Math.max(68, confidence)
  };
}

// Real-Time Optical Dosimetry Estimator strictly adhering to Stage 1-5 & Out-of-Calibration Rules
export function estimateDoseFromLab(
  sampledLab: { L: number; a: number; b: number },
  ambientTempC: number = 28.0,
  ambientRH: number = 55.0,
  shelfAgeDays: number = 25
): {
  estimatedDosePpmH: number;
  deltaE: number;
  status: ExposureStatus;
  confidenceScore: number;
  matchedSample: CalibrationSample;
  stageName: string;
  isOutOfCalibration: boolean;
  colorName: string;
} {
  const dE = deltaE76(sampledLab, CU_PAN_BASELINE);

  // 1. OUT OF CALIBRATION CHECK:
  // Rule: Beige / Brown or Dark Brown / Black -> OUT OF CALIBRATION // DO NOT ESTIMATE
  // Dark brown / black: L* < 28 or (L < 35 and low chroma)
  // Beige / brown: L* between 35-72 with low chroma (a* < 16, b* between -5 and 22) or degraded matrix
  const chroma = Math.sqrt(sampledLab.a * sampledLab.a + sampledLab.b * sampledLab.b);
  const isDarkBrownBlack = sampledLab.L < 28 || (sampledLab.L < 34 && chroma < 18);
  const isBeigeBrown = (sampledLab.L >= 34 && sampledLab.L <= 72 && chroma < 15) || 
                       (shelfAgeDays > 90) || 
                       (sampledLab.L > 42 && sampledLab.a < 18 && sampledLab.b > -10 && sampledLab.b < 5);

  if (isDarkBrownBlack || isBeigeBrown) {
    const expiredMatch = CALIBRATION_DATASET.find(s => s.visualStage.includes('Expired')) || CALIBRATION_DATASET[240];
    return {
      estimatedDosePpmH: 0,
      deltaE: dE,
      status: 'OUT_OF_CALIBRATION',
      confidenceScore: 0,
      matchedSample: expiredMatch,
      stageName: isDarkBrownBlack ? 'OUT OF CALIBRATION: Dark brown / black' : 'OUT OF CALIBRATION: Beige / brown',
      isOutOfCalibration: true,
      colorName: isDarkBrownBlack ? 'Dark brown / black' : 'Beige / brown'
    };
  }

  // 2. STAGE 1-5 CLASSIFICATION & INVERSE-DISTANCE WEIGHTING
  const validSamples = CALIBRATION_DATASET.filter(s => !s.visualStage.includes('Expired'));
  const sorted = [...validSamples]
    .map(s => ({
      sample: s,
      dist: Math.sqrt(
        Math.pow(s.lab.L - sampledLab.L, 2) +
        Math.pow(s.lab.a - sampledLab.a, 2) +
        Math.pow(s.lab.b - sampledLab.b, 2)
      )
    }))
    .sort((a, b) => a.dist - b.dist);

  const bestMatch = sorted[0]?.sample || validSamples[0];

  let totalWeight = 0;
  let weightedDose = 0;
  for (let i = 0; i < Math.min(3, sorted.length); i++) {
    const weight = 1 / (sorted[i].dist + 0.05);
    totalWeight += weight;
    weightedDose += sorted[i].sample.targetDose * weight;
  }
  let estimatedDose = Number((weightedDose / Math.max(0.001, totalWeight)).toFixed(3));

  // Arrhenius temperature and humidity correction
  const tempCorrection = 1 + (ambientTempC - 25) * 0.0075;
  const rhCorrection = 1 + (ambientRH - 50) * 0.0028;
  estimatedDose = Number((estimatedDose / (tempCorrection * rhCorrection)).toFixed(2));
  if (estimatedDose < 0) estimatedDose = 0;

  // Apply user rules strictly:
  // Stage 1: Deep violet / purple (~0–0.49 ppm·h) -> NORMAL
  // Stage 2: Violet-purple / reddish-purple (~0.50–0.99 ppm·h) -> MONITOR
  // Stage 3: Reddish / pink (~1.00–2.00 ppm·h) -> REVIEW
  // Stage 4: Orange / amber-orange (~2–10 ppm·h) -> REVIEW
  // Stage 5: Yellow / yellow-orange (~10–30+ ppm·h) -> REVIEW
  let status: ExposureStatus = 'NORMAL';
  let stageName = '';
  let colorName = '';

  if (estimatedDose < 0.50) {
    status = 'NORMAL';
    stageName = 'Stage 1: Fresh Unexposed (Deep Purple / Violet)';
    colorName = 'Deep violet / purple';
  } else if (estimatedDose < 1.00) {
    status = 'MONITOR';
    stageName = 'Stage 2: Trace Baseline Exposure (Violet-Purple)';
    colorName = 'Violet-purple / reddish-purple';
  } else if (estimatedDose <= 2.00) {
    status = 'REVIEW';
    stageName = 'Stage 3: Intermediate Action Level (Reddish-Pink)';
    colorName = 'Reddish / pink';
  } else if (estimatedDose < 10.00) {
    status = 'REVIEW';
    stageName = 'Stage 4: Elevated Exposure (Orange-Red to Amber-Orange)';
    colorName = 'Orange / amber-orange';
  } else {
    status = 'REVIEW';
    stageName = 'Stage 5: High / Saturated Overexposure (Vivid Yellow-Orange)';
    colorName = 'Yellow / yellow-orange';
  }

  const matchDistance = sorted[0]?.dist || 0;
  let confidence = 98 - Math.min(25, Math.round(matchDistance * 1.4));
  if (ambientTempC > 40 || ambientTempC < 15) confidence -= 5;
  if (ambientRH > 85 || ambientRH < 30) confidence -= 5;
  confidence = Math.max(74, confidence);

  return {
    estimatedDosePpmH: estimatedDose,
    deltaE: dE,
    status,
    confidenceScore: confidence,
    matchedSample: bestMatch,
    stageName,
    isOutOfCalibration: false,
    colorName
  };
}
