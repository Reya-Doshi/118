export function mapActionFlagToSafetyStatus(flag: string, expiry: string): ExposureStatus {
  if (expiry === 'EXPIRED' || flag.includes('Expired') || flag.includes('Reject') || flag.includes('Out of Calibration')) return 'OUT_OF_CALIBRATION';
  if (flag.includes('Stage 3') || flag.includes('Stage 4') || flag.includes('Stage 5') || flag.includes('Intermediate') || flag.includes('Elevated') || flag.includes('Saturated')) return 'REVIEW';
  if (flag.includes('Stage 2') || flag.includes('Trace') || flag.includes('Action Level')) return 'MONITOR';
  return 'NORMAL';
}

